def choose(moment: str, lang: str, recent: list, rng=random) -> int:
    """An index into the pool, avoiding the lines shown recently in this fight."""
    pool = (FA if lang == "fa" else EN).get(moment) or []
    if not pool:
        return -1
    free = [i for i in range(len(pool)) if f"{moment}:{i}" not in recent]
    return rng.choice(free or list(range(len(pool))))


def line(e: dict, lang: str) -> str:
    pool = (FA if lang == "fa" else EN).get(e.get("m")) or []
    if not pool:
        return ""
    i = int(e.get("i", 0)) % len(pool)
    if lang != "fa":  # the English set is smaller: map the Persian index onto it
        i = int(e.get("i", 0)) % len(pool)
    return pool[i].format(p=e.get("p", ""), f=e.get("f", ""))
